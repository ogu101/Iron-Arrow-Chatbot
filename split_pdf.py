"""
split_pdf.py — Split Iron Arrow history PDF into sections and generate metadata.

Usage:
    python3 split_pdf.py --input "iron-arrow-history.pdf" --output_dir ./section

Outputs:
    sections/         ← split PDFs, one per section
    chunks/           ← 4-layer JSON chunks per section
    resources.xlsx    ← metadata table for the chatbot

──────────────────────────────────────────────────────────────
JSON CHUNK STRUCTURE (4 layers)
──────────────────────────────────────────────────────────────
layer0_index      Always in system prompt. Key/name/description/subsections/
                  one-sentence summary. Never fetched via tool.

layer1_summary    First tool call result. One thematic paragraph + 5 tight
                  narrative bullets covering the whole section at a glance.
                  Sufficient for general "what is this section about?" queries.

layer2_details    Second tool call result. Subsection-by-subsection fact
                  bullets — names, dates, key events, causal logic. Sufficient
                  for specific factual queries without loading the full PDF text.

layer3_full_text  Third tool call result (rarely needed). Raw text extracted
                  from the split PDF at runtime — for exact quotes, fine-grained
                  detail, or anything layer2_details doesn't cover.

Layers 1 and 2 are generated by Claude (claude-sonnet-4-6) during preprocessing
using the extracted PDF text as source. Layer 3 is extracted live from the split
PDF at query time; it is NOT stored in the JSON to keep chunk files lightweight.
──────────────────────────────────────────────────────────────
"""

